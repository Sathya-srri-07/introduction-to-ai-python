# Data Types in Python

name = "Sathya"       # String
age = 19              # Integer
cgpa = 8.81           # Float
is_student = True     # Boolean

print("Name:", name)
print("Type:", type(name))

print("Age:", age)
print("Type:", type(age))

print("CGPA:", cgpa)
print("Type:", type(cgpa))

print("Student:", is_student)
print("Type:", type(is_student))
